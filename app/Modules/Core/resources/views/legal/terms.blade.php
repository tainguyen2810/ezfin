    description="Điều khoản sử dụng website EzFin: phạm vi thông tin, trách nhiệm, sở hữu nội dung và liên kết bên ngoài.">
    <p>Khi truy cập và sử dụng EzFin (ezfin.vn và app.ezfin.vn), bạn đồng ý với các điều khoản dưới đây. Nếu không đồng ý, vui lòng ngừng sử dụng website.</p>

    <h2>1. Tính chất thông tin</h2>
    <ul>
        <li>Thông tin trên EzFin, gồm lãi suất, phí, điều kiện sản phẩm, kết quả công cụ tính và bài viết, chỉ nhằm mục đích tham khảo và giáo dục tài chính.</li>
        <li>EzFin không phải ngân hàng, công ty chứng khoán hay đơn vị tư vấn đầu tư. Thông tin không phải lời khuyên tài chính, đầu tư, pháp lý hay thuế cho trường hợp riêng của bạn.</li>
        <li>Kết quả công cụ tính là ước tính theo công thức và giả định được nêu kèm. Số thực tế phụ thuộc hợp đồng giữa bạn và tổ chức tài chính.</li>
    </ul>

    <h2>2. Độ chính xác</h2>
    <p>EzFin lấy dữ liệu từ nguồn chính thức và ghi ngày xác minh cho từng sản phẩm (xem <a href="{{ route('legal.methodology') }}">Phương pháp đánh giá</a>). Tuy vậy, tổ chức tài chính có thể thay đổi sản phẩm bất kỳ lúc nào. Bạn cần xác nhận lại với tổ chức phát hành trước khi quyết định. EzFin không chịu trách nhiệm về thiệt hại phát sinh từ việc chỉ dựa vào thông tin trên website.</p>

    <h2>3. Liên kết bên ngoài</h2>
    <p>Website có liên kết tới trang của ngân hàng, tổ chức tài chính và bên thứ ba, trong đó có liên kết đối tác (xem <a href="{{ route('legal.disclosure') }}">Công bố liên kết</a>). Nội dung, sản phẩm và chính sách của các trang đó thuộc trách nhiệm của bên sở hữu.</p>

    <h2>4. Sở hữu nội dung</h2>
    <p>Bài viết, dữ liệu tổng hợp, giao diện và mã nguồn của EzFin thuộc sở hữu của EzFin. Bạn được trích dẫn ngắn kèm liên kết về trang gốc. Không sao chép hàng loạt, thu thập tự động hay sử dụng cho mục đích thương mại khi chưa có đồng ý bằng văn bản.</p>

    <h2>5. Sử dụng hợp lệ</h2>
    <p>Bạn không được dùng website để phát tán mã độc, truy cập trái phép, gây quá tải hệ thống hoặc vi phạm pháp luật Việt Nam. EzFin có thể chặn truy cập có dấu hiệu lạm dụng.</p>

    <h2>6. Quyền riêng tư</h2>
    <p>Cách EzFin xử lý dữ liệu được mô tả tại <a href="{{ route('legal.privacy') }}">Quyền riêng tư</a>.</p>

    <h2>7. Thay đổi điều khoản</h2>
    <p>EzFin có thể cập nhật điều khoản khi bổ sung tính năng. Ngày cập nhật ghi ở đầu trang. Tiếp tục sử dụng sau khi cập nhật nghĩa là bạn đồng ý với điều khoản mới.</p>

    <h2>8. Luật áp dụng</h2>
    <p>Điều khoản này được điều chỉnh theo pháp luật Việt Nam.</p>
